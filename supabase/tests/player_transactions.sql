begin;
do $$
declare admin_id uuid := gen_random_uuid(); member_id uuid := gen_random_uuid(); target uuid := gen_random_uuid();
  payload jsonb; saved public.players; blocked boolean;
begin
  insert into auth.users(id) values(admin_id),(member_id);
  update public.profiles set role='admin',active=true where id=admin_id;
  update public.profiles set active=true where id=member_id;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  execute 'set local role authenticated';
  payload := jsonb_build_object('id',target,'name','Teste transacional','number',10,'position','Meio-campo','active',true);
  blocked := false;
  begin perform public.save_player(payload,'{"cpf":"11111111111"}',null);
  exception when check_violation then blocked:=true; end;
  if not blocked or exists(select 1 from public.players where id=target) then raise exception 'Gravação parcial indevida.'; end if;
  select * into saved from public.save_player(payload,'{}',null);
  if saved.version<>1 then raise exception 'Versão inicial inválida.'; end if;
  select * into saved from public.save_player(payload || '{"name":"Editado"}','{"email":"teste@example.invalid"}',1);
  if saved.version<>2 then raise exception 'Versão não atualizada.'; end if;
  blocked:=false;
  begin perform public.save_player(payload,'{}',1);
  exception when serialization_failure then blocked:=true; end;
  if not blocked then raise exception 'Edição concorrente sobrescreveu dados.'; end if;
  blocked:=false;
  begin perform public.delete_player(target,1);
  exception when serialization_failure then blocked:=true; end;
  if not blocked then raise exception 'Exclusão com versão antiga permitida.'; end if;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',member_id::text,true);
  execute 'set local role authenticated';
  blocked:=false;
  begin perform public.save_player(payload,'{}',2);
  exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Membro gravou jogador.'; end if;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  execute 'set local role authenticated';
  perform public.delete_player(target,2);
  if exists(select 1 from public.player_private_details where player_id=target) then raise exception 'Dados privados órfãos.'; end if;
  execute 'reset role';
end;
$$;
rollback;
select 'OK: transações, conflitos e permissões de jogadores validados.' as resultado;
