begin;
do $$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); athlete uuid:=gen_random_uuid(); opponent uuid:=gen_random_uuid(); game uuid:=gen_random_uuid(); poll uuid:=gen_random_uuid();
  blocked boolean; v integer; week date:=date_trunc('week',now() at time zone 'America/Sao_Paulo')::date; payload jsonb; saved public.weekly_polls;
begin
  insert into auth.users(id,email) values(a,'admin-test@example.invalid'),(b,'member-test@example.invalid');
  update public.profiles set role='admin',active=true where id=a;
  perform set_config('request.jwt.claim.sub',a::text,true);
  execute 'set local role authenticated';
  if not exists(select 1 from public.admin_members() where id=b and not active) then raise exception 'Usuário pendente não listado.'; end if;
  blocked:=false;
  begin perform public.manage_member(a,'Admin','player',false); exception when raise_exception then blocked:=true; end;
  if not blocked then raise exception 'Último admin removido.'; end if;
  perform public.manage_member(b,'Comissão','staff',true);
  insert into public.players(id,name,number,position) values(athlete,'Atleta SQL',9,'Atacante');
  insert into public.opponents(id,name,initials) values(opponent,'Adversário SQL','ADV');
  insert into public.matches(id,opponent_id,starts_at,venue,status,goals_for,goals_against)
    values(game,opponent,week::timestamp at time zone 'America/Sao_Paulo','Arena','Finalizado',2,0);
  blocked:=false;
  begin perform public.save_participations(game,1,jsonb_build_array(jsonb_build_object('player_id',athlete,'goals',3)));
  exception when raise_exception then blocked:=true; end;
  if not blocked then raise exception 'Gols maiores que placar.'; end if;
  v:=public.save_participations(game,1,jsonb_build_array(jsonb_build_object('player_id',athlete,'goals',2)));
  if v<>2 or not exists(select 1 from public.match_players where match_id=game and goals=2) then raise exception 'Participação não gravada.'; end if;
  blocked:=false;
  begin perform public.save_participations(game,1,'[]'); exception when serialization_failure then blocked:=true; end;
  if not blocked then raise exception 'Conflito não bloqueado.'; end if;
  payload:=jsonb_build_object('id',poll,'week_start',week,'title','Craque SQL','opens_at',now()-interval '1 hour','closes_at',now()+interval '1 hour','state','draft');
  select * into saved from public.save_poll(payload,array[game],array[athlete],null);
  select * into saved from public.save_poll(payload||'{"title":"Editado","state":"published"}',array[game],array[athlete],saved.version);
  if saved.state<>'published' then raise exception 'Votação não publicada.'; end if;
  update public.matches set published=true where id=game;
  if not exists(select 1 from public.matches where id=game and published) then raise exception 'Publicação na agenda bloqueada.'; end if;
  update public.matches set published=false where id=game;
  blocked:=false;
  begin update public.matches set goals_for=3,published=true where id=game; exception when raise_exception then blocked:=true; end;
  if not blocked then raise exception 'Placar de votação publicada alterado.'; end if;
  select version into v from public.matches where id=game;
  blocked:=false;
  begin perform public.delete_poll(poll,saved.version); exception when serialization_failure then blocked:=true; end;
  if not blocked then raise exception 'Votação publicada excluída.'; end if;
  blocked:=false;
  begin perform public.save_participations(game,v,'[]'); exception when raise_exception then blocked:=true; end;
  if not blocked then raise exception 'Participação publicada alterada.'; end if;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',b::text,true);
  execute 'set local role authenticated';
  blocked:=false;
  begin perform public.manage_member(b,'Ataque','admin',true); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Autopromoção permitida.'; end if;
  blocked:=false;
  begin perform * from public.admin_members(); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'Email exposto ao membro.'; end if;
  perform public.cast_vote(poll,athlete);
  if not public.has_voted(poll) then raise exception 'Voto da comissão não salvo.'; end if;
  execute 'reset role';
end;
$$;
rollback;
select 'OK: gestão de membros, participações, publicação e voto validados.' as resultado;
